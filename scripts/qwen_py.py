from transformers import AutoTokenizer, AutoModelForCausalLM
import torch

model_name = "Qwen/Qwen3-4B-Instruct-2507"
tokenizer = AutoTokenizer.from_pretrained(model_name)
model =  AutoModelForCausalLM.from_pretrained(model_name, torch_dtype=torch.float16, device_map="auto")

# only for test
from google.colab import files
uploaded = files.upload()

# check if the 5 papers are loaded
import json
with open("top_5_papers.json", "r", encoding="utf-8") as f:
    top_papers = json.load(f)

print("Papers loaded:", len(top_papers))

#add timing
import time
llm_start = time.perf_counter()

#Qwen analysis loop on those 5 papers (support / contradict / unclear) + save into evidence_results.json
claim = "Vitamin C prevents the common cold."

results = []

for i, paper in enumerate(top_papers, 1):
    paper_title = paper.get("title", "")

    #Use RAG if available
    paper_evidence = paper.get("relevant_chunks") or paper.get("abstract") or ""

    prompt = f"""
You are evaluating scientific evidence for a claim.

Claim:
{claim}

Paper title:
{paper_title}

Relevant evidence:
{paper_evidence}

Classify the paper's evidence ONLY with respect to the exact claim.

Use exactly one of:
- support
- contradict
- unclear

Important:
If the paper explicitly says the claimed effect does not occur, classify as contradict.
Do not classify as unclear merely because the paper discusses other related benefits.
Do not use outside knowledge.

Return ONLY valid JSON in exactly this format:

{{
  "classification": "support | contradict | unclear",
  "explanation": "short explanation"
}}
"""

    messages = [
        {"role": "user", "content": prompt}
    ]

    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True
    )

    inputs = tokenizer(
        text,
        return_tensors="pt"
    ).to(model.device)

    outputs = model.generate(
        **inputs,
        max_new_tokens=120,
        do_sample=False
    )

    response = tokenizer.decode(
        outputs[0][inputs["input_ids"].shape[1]:],
        skip_special_tokens=True
    )

    try:
        analysis = json.loads(response)
    except json.JSONDecodeError:
        analysis = {
            "classification": "unclear",
            "explanation": "Model output could not be parsed as valid JSON.",
            "raw_output": response
        }

    results.append({
    "paper_id": paper.get("paper_id"),
    "title": paper_title,
    "year": paper.get("year"),
    "authors": paper.get("authors"),
    "url": paper.get("url"),
    "doi": paper.get("doi"),
    "is_open_access": paper.get("is_open_access"),
    "open_access_pdf": paper.get("open_access_pdf"),
    "relevance_score": paper.get("relevance_score"),
    "classification": analysis["classification"],
    "explanation": analysis["explanation"]
    })

    print(f"\n--- Paper {i} ---")
    print(results[-1])

with open("evidence_results.json", "w", encoding="utf-8") as f:
    json.dump(results, f, indent=2, ensure_ascii=False)

print("\nSaved to evidence_results.json")

#turning the five classifications we already have into the overall verdict  for UI

support_count=0
contradict_count=0
unclear_count=0

for paper in results:
  classification = paper["classification"].lower()

  if classification == "support":
     support_count += 1
  elif classification == "contradict":
     contradict_count += 1
  else:
    unclear_count +=1

if support_count > 0 and contradict_count > 0:
  verdict = "Mixed evidence"
elif support_count > 0 and contradict_count == 0:
  verdict = "Supported"
elif support_count == 0 and contradict_count > 0:
  verdict = "Refuted"
else:
  verdict = "Not enough evidence"

print("Support", support_count)
print("Contradict", contradict_count)
print("Unclear", unclear_count)
print("Verdict", verdict)

# Converts the 5 classifications to the final answer text that the UI will display


evidence_text = ""

for i, paper in enumerate(results, 1):
    evidence_text += f"""
Paper {i}
Title: {paper['title']}
Classification: {paper['classification']}
Explanation: {paper['explanation']}
"""

prompt = f"""
You are writing the final answer for an evidence-checking system.

Claim:
{claim}

Overall verdict:
{verdict}

Evidence from selected papers:
{evidence_text}

Write a short final answer for the user.

Requirements:
- Start by clearly stating the overall verdict.
- Summarize the evidence fairly.
- Mention that the evidence is mixed if papers disagree.
- Do not introduce outside knowledge.
- Do not invent facts.
- Keep the answer concise.
"""

messages = [
    {"role": "user", "content": prompt}
]

text = tokenizer.apply_chat_template(
    messages,
    tokenize=False,
    add_generation_prompt=True
)

inputs = tokenizer(
    text,
    return_tensors="pt"
).to(model.device)

outputs = model.generate(
    **inputs,
    max_new_tokens=180,
    do_sample=False
)

final_answer = tokenizer.decode(
    outputs[0][inputs["input_ids"].shape[1]:],
    skip_special_tokens=True
)

print(final_answer)

llm_end = time.perf_counter()
llm_generation_time = llm_end - llm_start

print("LLM generation time=", round(llm_generation_time,2), "seconds")

# reason_selected field
for paper in results:
    paper["reason_selected"] = (
        "Selected among the highest-ranked semantically relevant papers "
        "with available evidence for analysis"
    )

#a single backend response object that contains everything the UI need + save to backend_response.json

backend_response = {"final_answer": final_answer,
                    "verdict": verdict,
                    "sources": results,
                    "timing": {"llm_generation": round(llm_generation_time,2)}}
print(json.dumps(backend_response, indent=2, ensure_ascii=False))


